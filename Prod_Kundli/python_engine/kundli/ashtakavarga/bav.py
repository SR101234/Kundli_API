def calculate_bav(
    planet_sign_indices: Dict[str, int],
    ascendant_sign_index: int
) -> Dict[str, List[int]]:
    """Calculate the 12-sign Bhinnashtakavarga bindus (0 to 8) for each of the 7 planets.
    Returns: Dict[planet_name, List[bindus in Aries..Pisces]]
    """
    reference_signs = dict(planet_sign_indices)
    reference_signs["Ascendant"] = ascendant_sign_index

    bav_tables: Dict[str, List[int]] = {}

    for target_planet, rule_set in BAV_RULES.items():
        # 12 signs initialized to 0 bindus
        sign_bindus = [0] * 12

        for ref_point, houses in rule_set.items():
            if ref_point not in reference_signs:
                continue
            ref_sign = reference_signs[ref_point]
            for h in houses:
                target_sign = (ref_sign + h - 1) % 12
                sign_bindus[target_sign] += 1

        bav_tables[target_planet] = sign_bindus

    return bav_tables
